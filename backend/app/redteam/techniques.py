DOCX_TECHNIQUES = ["docx_hidden_run", "docx_white", "docx_tiny", "zero_width", "unicode_tags", "docx_metadata"]
ALL_TECHNIQUES = PDF_TECHNIQUES + DOCX_TECHNIQUES

