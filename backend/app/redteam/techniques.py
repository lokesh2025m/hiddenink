# Techniques that can be stacked on the same text (PDF).
STACKABLE = {"low_contrast", "tiny_font"}

WATERMARK = "HIDDENINK TEST FILE - generated by the Red-Team Lab"


def _font_for(text: str) -> str:
    return "china-s" if any(ord(c) > 0x2E80 for c in text) else "helv"


def _fit(page, rect, text, **kw) -> None:
    size = kw.pop("fontsize", 9)
    for _ in range(12):
        rc = page.insert_textbox(rect, text, fontsize=size, fontname=_font_for(text), **kw)
        if rc >= 0:
            return
        rect = pymupdf.Rect(rect.x0, rect.y0, rect.x1, rect.y1 + max(10, rect.height))
    page.insert_textbox(rect, text, fontsize=max(0.5, size / 2), fontname=_font_for(text), **kw)


def _rand_rect(free, rng: random.Random, h: float) -> pymupdf.Rect:
    x0, y0, x1, y1 = rng.choice(free)
    top = rng.uniform(y0, max(y0, y1 - h))
    return pymupdf.Rect(x0, top, x1, top + h)


def apply_pdf(doc, free, technique: str, fragments: list[str], rng: random.Random, stack: str | None) -> dict:
    page = doc[0]
    params: dict = {"technique": technique, "stacked_with": stack, "fragments": len(fragments), "locations": []}
    for frag in fragments:
        if technique in ("metadata",):
            meta = doc.metadata or {}
            field = rng.choice(["subject", "keywords", "title"])
            meta[field] = ((meta.get(field) or "") + " " + frag).strip()
            doc.set_metadata(meta)
            params["locations"].append({"field": field})
            continue
        if technique == "annotation":
            r = _rand_rect(free, rng, 20)
            a = page.add_text_annot(r.tl, frag)
            a.set_flags(pymupdf.PDF_ANNOT_IS_HIDDEN)
            a.update()
            params["locations"].append({"rect": list(r)})
            continue

        size = rng.uniform(6, 10)
        color = (0, 0, 0)
        kw: dict = {}
        bg_match = False
        if technique == "low_contrast" or stack == "low_contrast":
            if rng.random() < 0.35:
                # Match the light header band exactly (text on a coloured background).
                r = pymupdf.Rect(300, 22, samples.PAGE_W - 20, 56)
                color = (0.93, 0.95, 0.99)
                bg_match = params["background_match"] = True
            else:
                g = rng.uniform(0.95, 1.0)
                color = (g, g, g)
            params["color"] = [round(c, 3) for c in color]
        if technique == "tiny_font" or stack == "tiny_font":
            size = rng.uniform(0.5, 2.5)
        params["fontsize"] = round(size, 2)

        if technique == "off_page":
            if rng.random() < 0.5:
                x = samples.PAGE_W + rng.uniform(20, 200)
                r = pymupdf.Rect(x, rng.uniform(100, 600), x + 300, 0)
            else:
                y = -rng.uniform(80, 300)
                r = pymupdf.Rect(60, y, 500, 0)
            r.y1 = r.y0 + 60
        elif not bg_match:
            r = _rand_rect(free, rng, 40)

        if technique == "invisible_render":
            kw["render_mode"] = 3
        if technique == "transparent":
            kw["fill_opacity"] = 0.0
        if technique == "covered":
            color = (0.1, 0.1, 0.1)
        _fit(page, r, frag, fontsize=size, color=color, **kw)
        if technique == "covered":
            page.draw_rect(r, color=None, fill=(1, 1, 1), overlay=True)
        params["locations"].append({"rect": [round(v, 1) for v in r]})
    return params


def apply_docx(d, technique: str, fragments: list[str], rng: random.Random) -> dict:
    params: dict = {"technique": technique, "fragments": len(fragments), "locations": []}
    paras = [(i, p) for i, p in enumerate(d.paragraphs) if p.text.strip()]
    for frag in fragments:
        if technique == "docx_metadata":
            field = rng.choice(["subject", "keywords", "comments"])
            value = ((getattr(d.core_properties, field) or "") + " " + frag).strip()
            setattr(d.core_properties, field, value[:255])
            params["locations"].append({"field": field})
            continue
        idx, p = rng.choice(paras[2:] or paras)
        if technique in ("zero_width", "unicode_tags"):
            enc = uni.encode_zero_width_binary(frag) if technique == "zero_width" else uni.encode_tags(frag)
            p.add_run(enc)
        else:
            run = p.add_run(" " + frag)
            if technique == "docx_hidden_run":
                run.font.hidden = True
            elif technique == "docx_white":
                v = rng.randint(0xF2, 0xFF)
                run.font.color.rgb = RGBColor(v, v, v)
                params["color"] = f"{v:02X}{v:02X}{v:02X}"
            elif technique == "docx_tiny":
                size = round(rng.uniform(1, 2.5), 1)
                run.font.size = Pt(size)
                run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF) if rng.random() < 0.5 else None
                params["fontsize"] = size
        params["locations"].append({"paragraph": idx})
    return params


# ---------- invisibility check ----------
INK_DELTA = 40       # per-channel difference that counts as visible ink
INK_SHARE = 0.004    # share of pixels in the text box that must be ink for the text to be visible
READABLE_PT = 3.0    # text smaller than this is not readable at normal zoom


def verify_invisible_pdf(data: bytes, clean: bytes) -> tuple[bool, list[str]]:
    """Check that every injected span is truly invisible to a person; otherwise the attack is discarded.

    Injected spans are the ones that are not in the clean original (and are not the watermark)."""
    with pymupdf.open(stream=clean, filetype="pdf") as c:
        known = {"".join(chr(ch[0]) for ch in t["chars"]) for t in c[0].get_texttrace()}
    doc = pymupdf.open(stream=data, filetype="pdf")
    page = doc[0]
    pix = page.get_pixmap(dpi=150, alpha=False)
    arr = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, pix.n)[:, :, :3].astype(int)
    scale = 150 / 72
    traces = page.get_texttrace()
    problems: list[str] = []
    spans = [t for t in traces if "".join(chr(ch[0]) for ch in t["chars"]) not in known
             and WATERMARK not in "".join(chr(ch[0]) for ch in t["chars"])]
    if spans:  # metadata / annotation attacks put nothing on the page
        for t in spans:
            b = t["bbox"]
            if t["type"] == 3 or (t.get("opacity") or 0) < 0.1 or b[0] >= page.rect.x1 or b[3] <= page.rect.y0:
                continue
            if t["size"] < READABLE_PT:
                continue
            x0, y0 = max(0, int(b[0] * scale)), max(0, int(b[1] * scale))
            x1, y1 = min(pix.width, int(b[2] * scale) + 1), min(pix.height, int(b[3] * scale) + 1)
            region = arr[y0:y1, x0:x1].reshape(-1, 3)
            if region.size == 0:
                continue
            vals, counts = np.unique(region, axis=0, return_counts=True)
            bg = vals[counts.argmax()]
            ink = (np.abs(region - bg).max(axis=1) > INK_DELTA).mean()
            if ink > INK_SHARE:
                text = "".join(chr(ch[0]) for ch in t["chars"])
                problems.append(f"Injected text may be visible (ink {ink:.1%}): {text[:40]}")
    doc.close()
    return (not problems), problems
