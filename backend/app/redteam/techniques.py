"""Hiding techniques with randomised parameters.

Each function writes `payload` into a document and returns the parameters it
used, which go into the answer key. Everything is driven by a seeded RNG so any
attack can be regenerated exactly.
"""
from __future__ import annotations

import random

import numpy as np
import pymupdf
from docx.shared import Pt, RGBColor

from ..forensics import unicode as uni
