"""Layer 1 forensics for DOCX files."""
from __future__ import annotations

import io
import re
import zipfile
from dataclasses import dataclass, field

import docx
from docx.oxml.ns import qn

from . import unicode as uni
from .unicode import meta_worth_reporting as _meta_worth_reporting

TINY_FONT_PT = 4.0


@dataclass
class DocxRun:
    index: int
    text: str
    techniques: list[str] = field(default_factory=list)
    details: list[str] = field(default_factory=list)

    @property
    def hidden(self) -> bool:
        return bool(self.techniques)


@dataclass
class DocxAnalysis:
    runs: list[DocxRun]
    doc_findings: list[dict]
    machine_text: str
    visible_text: str


def _iter_paragraphs(d):
    for p in d.paragraphs:
        yield p
    for t in d.tables:
        for row in t.rows:
            for cell in row.cells:
                yield from cell.paragraphs
    for section in d.sections:
        for part in (section.header, section.footer):
            yield from part.paragraphs


def _near_white(rgb) -> bool:
    return rgb is not None and all(c >= 0xEE for c in (rgb[0], rgb[1], rgb[2]))


def analyse_docx(data: bytes) -> DocxAnalysis:
    try:
        d = docx.Document(io.BytesIO(data))
    except Exception as exc:  # noqa: BLE001
        raise ValueError("Could not read this DOCX file.") from exc

    runs: list[DocxRun] = []
    machine_lines: list[str] = []
    visible_lines: list[str] = []
    for p in _iter_paragraphs(d):
        m_line, v_line = [], []
        for r in p.runs:
            if not r.text:
                continue
            run = DocxRun(index=len(runs), text=r.text)
            rpr = r._element.rPr
            if r.font.hidden or (rpr is not None and rpr.find(qn("w:vanish")) is not None):
                run.techniques.append("docx_hidden_run")
                run.details.append("Run is marked as hidden text (w:vanish).")
            color = r.font.color.rgb if r.font.color is not None and r.font.color.type is not None else None
            shaded = rpr is not None and (rpr.find(qn("w:shd")) is not None or rpr.find(qn("w:highlight")) is not None)
            if _near_white(color) and not shaded:
                run.techniques.append("low_contrast")
                run.details.append(f"Text colour #{color} is white or near-white.")
            if r.font.size is not None and r.font.size.pt < TINY_FONT_PT:
                run.techniques.append("tiny_font")
                run.details.append(f"Font size {r.font.size.pt:.1f}pt is too small to read.")
            runs.append(run)
            m_line.append(r.text)
            if not run.hidden:
                v_line.append(r.text)
        machine_lines.append("".join(m_line))
        visible_lines.append("".join(v_line))

    findings: list[dict] = []
    cp = d.core_properties
    meta = " | ".join(f"{k}: {v}" for k, v in (("title", cp.title), ("subject", cp.subject),
                                                 ("keywords", cp.keywords), ("comments", cp.comments)) if v)
    meta = meta.replace("generated by python-docx", "").strip(" |")
    if _meta_worth_reporting(meta):
        findings.append({"technique": "metadata", "page": None, "bbox": None, "text": meta,
                         "detail": "Document properties (not shown on the page)."})

    with zipfile.ZipFile(io.BytesIO(data)) as z:
        names = set(z.namelist())
        if "word/comments.xml" in names:
            text = _xml_text(z.read("word/comments.xml").decode("utf8", "ignore"))
            if text:
                findings.append({"technique": "docx_comment", "page": None, "bbox": None, "text": text,
                                 "detail": "Reviewer comments stored in the file."})
        body = z.read("word/document.xml").decode("utf8", "ignore") if "word/document.xml" in names else ""
        for descr in (t for t in re.findall(r"<wp:docPr[^>]*\sdescr=\"([^\"]+)\"", body) if len(t) >= 30):
            findings.append({"technique": "metadata", "page": None, "bbox": None, "text": descr,
                             "detail": "Image alt text (read by machines, rarely seen by people)."})

    machine = "\n".join(machine_lines)
    for u in uni.analyse(machine):
        findings.append({"page": None, "bbox": None, **u})

    return DocxAnalysis(runs=runs, doc_findings=findings, machine_text=machine,
                        visible_text=uni.strip_invisible("\n".join(l for l in visible_lines)))


def _xml_text(x: str) -> str:
    return re.sub(r"\s+", " ", " ".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", x))).strip()
